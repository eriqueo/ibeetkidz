import {
  existsSync,
  readFileSync,
  readdirSync,
  statSync,
  writeFileSync,
} from "node:fs";
import { join } from "node:path";

const check = process.argv.includes("--check");
const outputs = ["THIRD_PARTY_NOTICES.txt", "public/THIRD_PARTY_NOTICES.txt"];
const lock = JSON.parse(readFileSync("package-lock.json", "utf8"));
const assets = JSON.parse(readFileSync("legal/third-party-assets.json", "utf8"));
const generatedRuntimePackages = JSON.parse(
  readFileSync("legal/generated-runtime-packages.json", "utf8"),
);
const generatedRuntimePaths = new Set(
  generatedRuntimePackages.map((name) => `node_modules/${name}`),
);

function licensePath(packagePath) {
  const candidates = readdirSync(packagePath)
    .filter((name) => /^(license|copying)(\..*)?$/i.test(name))
    .sort((left, right) => left.localeCompare(right));
  if (candidates.length === 0) {
    throw new Error(`No license file found in ${packagePath}`);
  }
  return join(packagePath, candidates[0]);
}

function normalizedText(path) {
  return readFileSync(path, "utf8")
    .replace(/\r\n?/g, "\n")
    .split("\n")
    .map((line) => line.trimEnd())
    .join("\n")
    .trim();
}

const packages = Object.entries(lock.packages)
  .filter(
    ([path, metadata]) =>
      path.startsWith("node_modules/") &&
      (metadata.dev !== true || generatedRuntimePaths.has(path)),
  )
  .map(([path, metadata]) => {
    if (!existsSync(path)) {
      throw new Error(`Production package is not installed: ${path}; run npm ci`);
    }
    const manifest = JSON.parse(readFileSync(join(path, "package.json"), "utf8"));
    return {
      name: manifest.name,
      version: metadata.version,
      license: metadata.license ?? manifest.license ?? "UNKNOWN",
      text: normalizedText(licensePath(path)),
    };
  })
  .sort((left, right) => `${left.name}@${left.version}`.localeCompare(`${right.name}@${right.version}`));

for (const packagePath of generatedRuntimePaths) {
  if (!lock.packages[packagePath]) {
    throw new Error(`Generated runtime package is absent from package-lock.json: ${packagePath}`);
  }
}

for (const asset of assets) {
  if (!existsSync(asset.file) || statSync(asset.file).size === 0) {
    throw new Error(`Licensed asset is missing: ${asset.file}`);
  }
  if (!existsSync(asset.licenseFile)) {
    throw new Error(`Asset license is missing: ${asset.licenseFile}`);
  }
}

const sections = [
  "THIRD-PARTY NOTICES FOR IBEETKIDZ",
  "",
  "This file is generated by scripts/generate-third-party-notices.mjs.",
  "Regenerate it with: npm run generate:notices",
  "",
  "PRODUCTION JAVASCRIPT PACKAGES",
  ...packages.flatMap((pkg) => [
    "",
    "=".repeat(72),
    `${pkg.name}@${pkg.version} (${pkg.license})`,
    "=".repeat(72),
    pkg.text,
  ]),
  "",
  "BUNDLED FONT ASSETS",
];

for (const asset of assets) {
  sections.push(
    "",
    "=".repeat(72),
    `${asset.name} (${asset.license})`,
    "=".repeat(72),
    `File: ${asset.file}`,
    `Source: ${asset.source}`,
    asset.copyright,
    "",
    normalizedText(asset.licenseFile),
  );
}

const expected = `${sections.join("\n")}\n`;
if (check) {
  const stale = outputs.filter(
    (path) => !existsSync(path) || readFileSync(path, "utf8") !== expected,
  );
  if (stale.length > 0) {
    throw new Error(`Third-party notices are missing or stale: ${stale.join(", ")}`);
  }
  console.log(`ok: ${packages.length} production packages and ${assets.length} assets covered`);
} else {
  for (const path of outputs) writeFileSync(path, expected);
  console.log(`wrote ${outputs.join(" and ")}`);
}
